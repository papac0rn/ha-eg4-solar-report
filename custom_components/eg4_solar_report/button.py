_LOGGER = logging.getLogger(__name__)

DASHBOARD_URL = "eg4-solar-report"


def _dashboards_collection(hass: HomeAssistant) -> Any | None:
    """The storage collection behind Settings → Dashboards.

    Older Home Assistant kept it on hass.data["lovelace"]; newer versions only hand it to the
    lovelace/dashboards/* websocket commands, so it is found through the create command's handler.
    """
    lovelace = hass.data.get("lovelace")
    if lovelace is not None and getattr(lovelace, "dashboard_collection", None) is not None:
        return lovelace.dashboard_collection
    entry = hass.data.get("websocket_api", {}).get("lovelace/dashboards/create")
    if not entry:
        return None
    handler = inspect.unwrap(entry[0])
    owner = getattr(handler, "__self__", None)
    return getattr(owner, "storage_collection", None)


TARGET_NEW = "new"
TARGET_NONE = "none"
DEFAULT_DASHBOARD = "lovelace"  # stands for the Overview dashboard, whose url_path is None


def dashboard_choices(hass: HomeAssistant) -> list[tuple[str, str]]:
    """Dashboards a report tab can be added to: (value, label). Only UI-managed (storage) ones can be edited."""
    lovelace = hass.data.get("lovelace")
    out: list[tuple[str, str]] = []
    if lovelace is None:
        return out
    for url, dash in lovelace.dashboards.items():
        if getattr(dash, "mode", None) != "storage" or url == DASHBOARD_URL:
            continue
        title = (dash.config or {}).get("title") if url else "Overview"
        out.append((url or DEFAULT_DASHBOARD, f"A tab on {title or url}"))
    return sorted(out, key=lambda c: c[1].lower())


async def async_place_report(hass: HomeAssistant, entry: ConfigEntry, target: str) -> str:
    """Put the report where the owner chose; returns a short description of where it went."""
    if target == TARGET_NONE:
        return "nowhere"
    if target == TARGET_NEW:
        await async_create_dashboard(hass, entry)
        return "the Solar Report dashboard"
    lovelace = hass.data.get("lovelace")
    key = None if target == DEFAULT_DASHBOARD else target
    dash = lovelace.dashboards.get(key) if lovelace else None
    if dash is None or getattr(dash, "mode", None) != "storage":
        raise HomeAssistantError(f"The dashboard '{target}' can't be edited from here")
    try:
        config = await dash.async_load(False)
    except Exception as err:  # noqa: BLE001 - e.g. an Overview still auto-generated by Home Assistant
        raise HomeAssistantError(
            "That dashboard hasn't been taken over for editing yet. Open it, choose ⋮ → Edit dashboard → "
            "Take control, then try again, or pick a new Solar Report dashboard."
        ) from err
    # Keep a copy of the dashboard as it was, once, so the owner can always go back
    backup = Store(hass, 1, f"{DOMAIN}.backup.{target}")
    if await backup.async_load() is None:
        await backup.async_save(config)
    view = build_view(er.async_get(hass), entry.entry_id, "Solar Report")
    views = [v for v in config.get("views", []) if v.get("path") != VIEW_PATH]
    await dash.async_save({**config, "views": [*views, view]})
    title = ((dash.config or {}).get("title") if key else "Overview") or target
    return f"a Solar Report tab on {title}"


async def async_create_dashboard(hass: HomeAssistant, entry: ConfigEntry) -> None:
    """Create the "Solar Report" dashboard, or rewrite it. It only ever touches its own dashboard."""
    lovelace = hass.data.get("lovelace")
    if lovelace is None:
        raise HomeAssistantError("Dashboards aren't available")
    if DASHBOARD_URL not in lovelace.dashboards:
        collection = _dashboards_collection(hass)
        if collection is None:
            raise HomeAssistantError(
                "Couldn't create the dashboard automatically. Add one under Settings → Dashboards and see the "
                "Dashboard Guide for the cards."
            )
        await collection.async_create_item({
            "url_path": DASHBOARD_URL,
            "title": "Solar Report",
            "icon": "mdi:solar-power-variant",
            "require_admin": False,
            "show_in_sidebar": True,
        })
    dashboard = lovelace.dashboards.get(DASHBOARD_URL)
    if dashboard is None:
        raise HomeAssistantError("The Solar Report dashboard could not be created")
    config = build_dashboard(er.async_get(hass), entry.entry_id, f"Solar Report · {entry.title}")
    await dashboard.async_save(config)
    _LOGGER.info("Saved the Solar Report dashboard (%d cards)", len(config["views"][0]["cards"]))


async def async_setup_entry(
    hass: HomeAssistant, entry: ConfigEntry, async_add_entities: AddEntitiesCallback
) -> None:
    manager: ReportManager = hass.data[DOMAIN][entry.entry_id]
    async_add_entities([GenerateReportButton(manager, entry), CreateDashboardButton(manager, entry)])


class GenerateReportButton(ReportEntity, ButtonEntity):
    _attr_name = "Generate Report"
    _attr_icon = "mdi:file-chart"

    def __init__(self, manager: ReportManager, entry: ConfigEntry) -> None:
        super().__init__(manager, entry, "generate_report")

    async def async_press(self) -> None:
        # Downloads can take a while; don't hold the button press open
        self.hass.async_create_task(self._manager.async_generate())


class CreateDashboardButton(ReportEntity, ButtonEntity):
    """Rebuilds the report wherever the owner chose to put it (Configure → Report location)."""

    _attr_name = "Create Dashboard"
    _attr_icon = "mdi:view-dashboard-edit"
    _attr_entity_category = EntityCategory.CONFIG

    def __init__(self, manager: ReportManager, entry: ConfigEntry) -> None:
        super().__init__(manager, entry, "create_dashboard")

    async def async_press(self) -> None:
        target = report_location(self._entry)
        await async_place_report(self.hass, self._entry, TARGET_NEW if target == TARGET_NONE else target)


def report_location(entry: ConfigEntry) -> str:
    return entry.options.get(OPT_REPORT_LOCATION) or entry.data.get(OPT_REPORT_LOCATION) or TARGET_NEW
